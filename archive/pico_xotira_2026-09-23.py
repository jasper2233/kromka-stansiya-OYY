def oqish_vaqti():
    """Pico dan PING so'rab, xotira o'qilgan lahzani aniqlaydi."""
    if '--hozir' in sys.argv:
        return datetime.utcnow()
    import serial
    s = serial.Serial(PORT, 115200, timeout=0.5)
    try:
        s.reset_input_buffer()
        s.write(b'PING\n')
        t0 = time.time()
        while time.time() - t0 < 4:
            l = s.readline()
            if not l:
                continue
            try:
                d = json.loads(l.decode('utf-8', 'replace'))
            except ValueError:
                continue
            if d.get('ev') == 'pong':
                ofset = (d['up'] - UP_OQILGAN) / 1000.0
                print('Pico up=%d ms, o\'qishdan beri %.1f s o\'tdi' % (d['up'], ofset))
                return datetime.utcnow() - timedelta(seconds=ofset)
    finally:
        s.close()
    raise SystemExit('pong kelmadi — Pico javob bermayapti')


def iso(dt):
    return dt.strftime('%Y-%m-%dT%H:%M:%S.') + '%03dZ' % (dt.microsecond // 1000)


def main():
    t_oqish = oqish_vaqti()
    print('Xotira o\'qilgan lahza (UTC):', iso(t_oqish))
    ev = []
    for (n, L, L1, L2, d1, d2, v, ish, farq, eski) in OLCHOV:
        ts = t_oqish - timedelta(milliseconds=eski)
        kirish = ts - timedelta(milliseconds=ish + d2 / 1000.0)
        ev.append({'id': 'KROMKA-01-xot0923-%03d' % n, 'station': ST, 'ts': iso(ts),
                   'type': 'olchov', 'qr': None, 'name': None, 'expected_mm': None,
                   'measured_mm': L, 'delta_mm': None, 'side': None, 'verdict': 'SKANERSIZ',
                   'pico_kod': 'OK', 'suspect': 0, 'L1': L1, 'L2': L2,
                   'd1_us': d1, 'd2_us': d2, 'v_meas': v, 'v_nom': 18,
                   'ish_ms': ish, 'n': n, 'kirish_ts': iso(kirish), 'xotiradan': 1})
    for i, (holat, eski) in enumerate(USKUNA):
        ts = t_oqish - timedelta(milliseconds=eski)
        ev.append({'id': 'KROMKA-01-xot0923-u%02d' % i, 'station': ST, 'ts': iso(ts),
                   'type': 'uskuna', 'holat': holat, 'xotiradan': 1})
    ev.sort(key=lambda e: e['ts'])
    print('Yuboriladi: %d hodisa, %s .. %s' % (len(ev), ev[0]['ts'], ev[-1]['ts']))
